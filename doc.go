// Package h264 实现纯 Go 的 H.264/AVC 编解码器（Encoder + Decoder）。
//
// 公开入口只有三类：
//
//	Frame   未压缩图像：原生 YUV、平面存储、允许任意 Stride
//	Packet  压缩访问单元：Annex-B 或 AVCC 载荷
//	Encoder / Decoder  增量式 Send/Receive 状态机
//
// 约束（与本项目 docs/ 中的路线图一致，任何改动都必须先改文档）：
//
//  1. 禁止 CGO、禁止 C/C++ 源码、禁止链接外部编解码动态库。
//  2. 允许 Go 汇编（amd64 SSE2/AVX2、arm64 NEON），但每个汇编 kernel
//     必须存在 Go 标量实现，且两者输出必须逐元素一致。
//  3. 运行时只依赖标准库；FFmpeg 仅用于开发期差分验证（Oracle），
//     绝不进入运行时依赖。
//  4. 所有不可信输入（码流）都必须先做边界与上限检查，再进入算法。
//
// 设计取舍：内部一律使用原生 YUV，不做 RGB 转换。色度抽样与高位深打包
// 方式一旦偏离规范，逐像素比对就会出现系统性偏差，因此转换放在库外。
