// Package prediction 实现编解码共享的帧内与帧间预测。
//
// 帧内：4×4（9 模式）、8×8、16×16（4 模式）、色度 8×8/8×16（4 模式）。
// 帧间：运动补偿、亮度/4:4:4 色度 6-tap、4:2:0/4:2:2 色度双线性、加权预测。
//
// 关键约束：
//   - 预测只读取参考像素，不写目标平面；残差相加由调用方完成，
//     这样编码器的本地重建与解码器的重建可以共用同一条代码路径；
//   - 边界不可用的预测模式必须按规范回退（例如 8/10-bit 缺少两侧时
//     使用 128/512），回退规则写错会导致宏块左上角系统性偏色；
//   - 亚像素插值的舍入必须严格按规范，不能用"四舍五入"近似。
//   - byte 与 uint16 入口实例化同一份算术核心，跨度均以采样计；
//     六抽头双半像素不裁剪中间值，权重 offset 在内核按位深缩放。
//   - Chroma422 使用 Top[0:8]/Left[0:16]；Plane 两轴按各自尺寸归一化；
//   - ChromaSampleFormat/MCBlockChromaFormat 的 subW/subH 仅为
//     420=(2,2)、422=(2,1)、444=(1,1)，MV 始终以亮度四分之一像素计，
//     位置、宽高和 stride 仍以本平面采样计；旧色度入口固定为 420。
