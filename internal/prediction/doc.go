// Package prediction 实现编解码共享的帧内与帧间预测。
//
// 帧内：4×4（9 模式）、8×8、16×16（4 模式）、色度（4 模式）。
// 帧间：运动补偿、亮度 6-tap 插值、色度双线性插值、加权预测。
//
// 关键约束：
//   - 预测只读取参考像素，不写目标平面；残差相加由调用方完成，
//     这样编码器的本地重建与解码器的重建可以共用同一条代码路径；
//   - 边界不可用的预测模式必须按规范回退（例如缺失上/左像素时用 128
//     或邻近像素替换），回退规则写错会导致宏块左上角系统性偏色；
//   - 亚像素插值的舍入必须严格按规范，不能用"四舍五入"近似。
