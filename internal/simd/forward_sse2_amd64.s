//go:build amd64 && !purego

#include "textflag.h"

// 列变换、转置、列变换、转置；32位加减与Go的int32模运算一致。
// 输入/输出为ABI0栈上的64字节数组，只加载0..63并写出0..63，不要求对齐。
TEXT ·forward4SSE2(SB), NOSPLIT, $0-128
	LEAQ src+0(FP), SI
	MOVOU (SI), X0
	MOVOU 16(SI), X1
	MOVOU 32(SI), X2
	MOVOU 48(SI), X3

	MOVOU X0, X4
	MOVOU X1, X5
	PADDL X3, X4
	PADDL X2, X5
	PSUBL X3, X0
	PSUBL X2, X1
	MOVOU X4, X6
	PADDL X5, X6
	PSUBL X5, X4
	MOVOU X0, X5
	PADDL X0, X5
	PADDL X1, X5
	PADDL X1, X1
	PSUBL X1, X0
	MOVOU X0, X3
	MOVOU X6, X0
	MOVOU X5, X1
	MOVOU X4, X2

	MOVOU X0, X4
	MOVOU X0, X5
	PUNPCKLLQ X1, X4
	PUNPCKHLQ X1, X5
	MOVOU X2, X6
	MOVOU X2, X7
	PUNPCKLLQ X3, X6
	PUNPCKHLQ X3, X7
	MOVOU X4, X0
	MOVOU X4, X1
	PUNPCKLQDQ X6, X0
	PUNPCKHQDQ X6, X1
	MOVOU X5, X2
	MOVOU X5, X3
	PUNPCKLQDQ X7, X2
	PUNPCKHQDQ X7, X3

	MOVOU X0, X4
	MOVOU X1, X5
	PADDL X3, X4
	PADDL X2, X5
	PSUBL X3, X0
	PSUBL X2, X1
	MOVOU X4, X6
	PADDL X5, X6
	PSUBL X5, X4
	MOVOU X0, X5
	PADDL X0, X5
	PADDL X1, X5
	PADDL X1, X1
	PSUBL X1, X0
	MOVOU X0, X3
	MOVOU X6, X0
	MOVOU X5, X1
	MOVOU X4, X2

	MOVOU X0, X4
	MOVOU X0, X5
	PUNPCKLLQ X1, X4
	PUNPCKHLQ X1, X5
	MOVOU X2, X6
	MOVOU X2, X7
	PUNPCKLLQ X3, X6
	PUNPCKHLQ X3, X7
	MOVOU X4, X0
	MOVOU X4, X1
	PUNPCKLQDQ X6, X0
	PUNPCKHQDQ X6, X1
	MOVOU X5, X2
	MOVOU X5, X3
	PUNPCKLQDQ X7, X2
	PUNPCKHQDQ X7, X3

	LEAQ out+64(FP), DI
	MOVOU X0, (DI)
	MOVOU X1, 16(DI)
	MOVOU X2, 32(DI)
	MOVOU X3, 48(DI)
	RET

