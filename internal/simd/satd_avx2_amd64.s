//go:build amd64 && !purego

#include "textflag.h"

// 两个YMM分别存两行，每个128位lane独立水平蝶形，再做垂直蝶形。
// VPBLENDD、256位VPABSD执行真实AVX2，不依赖BMI/FMA。
TEXT ·satd4AVX2(SB), NOSPLIT, $0-72
	LEAQ src+0(FP), SI
	VMOVDQU (SI), Y0
	VMOVDQU 32(SI), Y1
	VPSHUFD $0x1b, Y0, Y2
	VPADDD Y2, Y0, Y3
	VPSUBD Y2, Y0, Y0
	VPSHUFD $0x44, Y0, Y0
	VPBLENDD $0xcc, Y0, Y3, Y0
	VPHADDD Y0, Y0, Y2
	VPHSUBD Y0, Y0, Y0
	VPUNPCKLQDQ Y0, Y2, Y0
	VPSHUFD $0x1b, Y1, Y2
	VPADDD Y2, Y1, Y3
	VPSUBD Y2, Y1, Y1
	VPSHUFD $0x44, Y1, Y1
	VPBLENDD $0xcc, Y1, Y3, Y1
	VPHADDD Y1, Y1, Y2
	VPHSUBD Y1, Y1, Y1
	VPUNPCKLQDQ Y1, Y2, Y1
	VEXTRACTI128 $1, Y0, X4
	VEXTRACTI128 $1, Y1, X5
	VPADDD X5, X0, X2
	VPADDD X1, X4, X3
	VPSUBD X5, X0, X0
	VPSUBD X1, X4, X4
	VPADDD X3, X2, X1
	VPSUBD X3, X2, X2
	VPADDD X4, X0, X3
	VPSUBD X4, X0, X0
	VINSERTI128 $1, X3, Y1, Y1
	VINSERTI128 $1, X0, Y2, Y2
	VPABSD Y1, Y1
	VPABSD Y2, Y2
	VPADDD Y2, Y1, Y1
	VEXTRACTI128 $1, Y1, X0
	VPADDD X0, X1, X1
	VPSHUFD $0x4e, X1, X0
	VPADDD X0, X1, X1
	VPSHUFD $0xb1, X1, X0
	VPADDD X0, X1, X1
	VMOVQ X1, AX
	ADDL $1, AX
	SARL $1, AX
	MOVLQSX AX, AX
	VZEROUPPER
	MOVQ AX, ret+64(FP)
	RET
