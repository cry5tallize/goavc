#define SIX_W PADDW X5,X0; PADDW X4,X1; MOVOU X1,X6; PSLLW $2,X1; PADDW X6,X1; PADDW X3,X2; MOVOU X2,X6; PSLLW $2,X2; PADDW X6,X2; PSLLW $2,X2; PSUBW X1,X0; PADDW X2,X0
