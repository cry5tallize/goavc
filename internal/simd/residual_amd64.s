//go:build amd64 && !purego

#include "textflag.h"

TEXT ·residualSSE2(SB), NOSPLIT, $0-96
	LEAQ a+0(FP), SI
	LEAQ b+32(FP), DI
	LEAQ ret+64(FP), BX
	MOVOU (SI), X0
	MOVOU 16(SI), X1
	MOVOU (DI), X2
	MOVOU 16(DI), X3
	PADDL X2, X0
	PADDL X3, X1
	MOVOU X0, (BX)
	MOVOU X1, 16(BX)
	RET
TEXT ·residualAVX2(SB), NOSPLIT, $0-96
	VMOVDQU a+0(FP), Y0
	VMOVDQU b+32(FP), Y1
	VPADDD Y1, Y0, Y0
	VMOVDQU Y0, ret+64(FP)
	VZEROUPPER
	RET
