// Package simd 是平台相关内核的唯一入口。
//
// 结构：generic.go 提供纯 Go 标量实现，amd64/arm64 汇编实现通过
// dispatch.go 在运行时选择；上层只调用 dispatch 暴露的函数指针/包装函数，
// 不允许直接 import 汇编符号。
//
// 关键约束：
//   - 每个 kernel 必须有对应的标量实现，且在任何 CPU 上都能工作；
//   - 汇编与标量实现的输出必须逐元素相等，边界（非对齐 stride、
//     奇数宽高、极值像素）必须有专门测试；
//   - 运行时分发只做一次（包初始化），热路径不允许反复查表；
//   - 不允许强制要求 AVX2：缺少 AVX2 时退化到 SSE2，再退化到标量。
