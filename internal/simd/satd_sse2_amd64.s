//go:build amd64 && !purego

#include "textflag.h"

// 32位Hadamard无中间舍入，两轴变换可交换。转置只改变系数排列，
// 最终sumAbs和旧实现一致；不使用饱和窄化或SSE4绝对值指令。
TEXT ·satd4SSE2(SB), NOSPLIT, $0-72
	LEAQ src+0(FP), SI
	MOVOU (SI), X0
	MOVOU 16(SI), X1
	MOVOU 32(SI), X2
	MOVOU 48(SI), X3
	MOVOU X0, X4
	MOVOU X1, X5
	PADDL X3, X4
	PADDL X2, X5
	PSUBL X3, X0
	PSUBL X2, X1
	MOVOU X4, X2
	MOVOU X0, X3
	PADDL X5, X4
	PSUBL X5, X2
	PADDL X1, X0
	PSUBL X1, X3
	MOVOU X4, X1
	PUNPCKLLQ X0, X4
	PUNPCKHLQ X0, X1
	MOVOU X2, X5
	PUNPCKLLQ X3, X2
	PUNPCKHLQ X3, X5
	MOVOU X4, X0
	PUNPCKLQDQ X2, X4
	PUNPCKHQDQ X2, X0
	MOVOU X1, X3
	PUNPCKLQDQ X5, X1
	PUNPCKHQDQ X5, X3
	MOVOU X4, X2
	MOVOU X0, X5
	PADDL X3, X2
	PADDL X1, X5
	PSUBL X3, X4
	PSUBL X1, X0
	MOVOU X2, X1
	MOVOU X4, X3
	PADDL X5, X2
	PSUBL X5, X1
	PADDL X0, X4
	PSUBL X0, X3
	MOVOU X2, X0
	PSRAL $31, X0
	PXOR X0, X2
	PSUBL X0, X2
	MOVOU X1, X0
	PSRAL $31, X0
	PXOR X0, X1
	PSUBL X0, X1
	MOVOU X4, X0
	PSRAL $31, X0
	PXOR X0, X4
	PSUBL X0, X4
	MOVOU X3, X0
	PSRAL $31, X0
	PXOR X0, X3
	PSUBL X0, X3
	PADDL X1, X2
	PADDL X4, X2
	PADDL X3, X2
	PSHUFD $0x4e, X2, X1
	PADDL X1, X2
	PSHUFD $0xb1, X2, X1
	PADDL X1, X2
	MOVQ X2, AX
	ADDL $1, AX
	SARL $1, AX
	MOVLQSX AX, AX
	MOVQ AX, ret+64(FP)
	RET
