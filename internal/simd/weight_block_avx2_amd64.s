// Spec:8.4.3.2。8采样/批，精确32位乘加；最大绝对分子<2^25。
// 加载恰好8/16字节，压缩前把两个128-bit lane拼接，所有返回执行VZEROUPPER。
#define PREP \
	MOVL coeff+104(FP),AX; MOVWQSX AX,DX; VMOVD DX,X10; VPBROADCASTD X10,Y10; \
	SHRL $16,AX; MOVWQSX AX,DX; VMOVD DX,X9; VPBROADCASTD X9,Y9; \
	MOVL bias+108(FP),AX; VMOVD AX,X11; VPBROADCASTD X11,Y11; \
	MOVL offset+112(FP),AX; VMOVD AX,X12; VPBROADCASTD X12,Y12; \
	MOVL shift+116(FP),AX; VMOVD AX,X13; VPXOR Y15,Y15,Y15

#define CALC \
	VPMULLD Y10,Y0,Y0; VPMULLD Y9,Y1,Y1; VPADDD Y1,Y0,Y0; \
	VPADDD Y11,Y0,Y0; VPSRAD X13,Y0,Y0; VPADDD Y12,Y0,Y0; \
	VPMAXSD Y15,Y0,Y0; VPMINSD Y14,Y0,Y0; VEXTRACTI128 $1,Y0,X1; VPACKSSDW X1,X0,X0

TEXT ·weightBlock8AVX2(SB), NOSPLIT, $0-120
	MOVQ dst_base+0(FP),DI
	MOVQ ds+24(FP),R8
	MOVQ a_base+32(FP),SI
	MOVQ b_base+56(FP),BX
	MOVQ ss+80(FP),R9
	MOVQ w+88(FP),R10
	MOVQ h+96(FP),R11
	PREP
	MOVL $255,AX
	VMOVD AX,X14
	VPBROADCASTD X14,Y14
wa8_row:
	XORQ CX,CX
wa8_batch:
	VPMOVZXBD (SI)(CX*1),Y0
	VPXOR Y1,Y1,Y1
	TESTQ BX,BX
	JEQ wa8_calc
	VPMOVZXBD (BX)(CX*1),Y1
wa8_calc:
	CALC
	VPACKUSWB X0,X0,X0
	VMOVQ X0,(DI)(CX*1)
	ADDQ $8,CX
	CMPQ CX,R10
	JLT wa8_batch
	ADDQ R8,DI
	ADDQ R9,SI
	TESTQ BX,BX
	JEQ wa8_next
	ADDQ R9,BX
wa8_next:
	DECQ R11
	JNE wa8_row
	VZEROUPPER
	RET

