// Spec: 8.7.2.4。8个16位lane保存8条线，所有候选都从原始p1/p0/q0/q1计算。
// 弱滤波分子范围[-1271,1279]、强滤波和范围[2,1022]，有符号16位精确。
// 垂直方向每行只读4字节，水平每行只读8字节；不要求额外padding。
TEXT ·filterChroma8EdgeSSE2(SB), NOSPLIT, $0-104
