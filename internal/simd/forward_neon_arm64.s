#include "textflag.h"

// 两轴32位整数蝶形，转置后恢复光栅系数；无饱和、浮点或可选指令。
// 与SSE2/Generic同一C基底与模运算，load/store各限固定数组0..63字节。
TEXT ·forward4NEON(SB), NOSPLIT, $0-128
	MOVD $src+0(FP), R0
	VLD1 (R0), [V0.S4, V1.S4, V2.S4, V3.S4]

	VADD V3.S4, V0.S4, V4.S4
	VADD V2.S4, V1.S4, V5.S4
	VSUB V3.S4, V0.S4, V6.S4
	VSUB V2.S4, V1.S4, V7.S4
	VADD V5.S4, V4.S4, V0.S4
	VSUB V5.S4, V4.S4, V2.S4
	VADD V6.S4, V6.S4, V8.S4
	VADD V7.S4, V8.S4, V1.S4
	VADD V7.S4, V7.S4, V8.S4
	VSUB V8.S4, V6.S4, V3.S4

	VZIP1 V1.S4, V0.S4, V4.S4
	VZIP2 V1.S4, V0.S4, V5.S4
	VZIP1 V3.S4, V2.S4, V6.S4
	VZIP2 V3.S4, V2.S4, V7.S4
	VZIP1 V6.D2, V4.D2, V0.D2
	VZIP2 V6.D2, V4.D2, V1.D2
	VZIP1 V7.D2, V5.D2, V2.D2
	VZIP2 V7.D2, V5.D2, V3.D2

	VADD V3.S4, V0.S4, V4.S4
	VADD V2.S4, V1.S4, V5.S4
	VSUB V3.S4, V0.S4, V6.S4
	VSUB V2.S4, V1.S4, V7.S4
	VADD V5.S4, V4.S4, V0.S4
	VSUB V5.S4, V4.S4, V2.S4
	VADD V6.S4, V6.S4, V8.S4
	VADD V7.S4, V8.S4, V1.S4
	VADD V7.S4, V7.S4, V8.S4
	VSUB V8.S4, V6.S4, V3.S4

	VZIP1 V1.S4, V0.S4, V4.S4
	VZIP2 V1.S4, V0.S4, V5.S4
	VZIP1 V3.S4, V2.S4, V6.S4
	VZIP2 V3.S4, V2.S4, V7.S4
	VZIP1 V6.D2, V4.D2, V0.D2
	VZIP2 V6.D2, V4.D2, V1.D2
	VZIP1 V7.D2, V5.D2, V2.D2
	VZIP2 V7.D2, V5.D2, V3.D2

	MOVD $out+64(FP), R0
	VST1 [V0.S4, V1.S4, V2.S4, V3.S4], (R0)
	RET

