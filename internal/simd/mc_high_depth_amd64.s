// Spec:8.4.2.2.1。两遍六抽头使用32位，中间不Clip；10-bit第二遍绝对值<2^22。
// 完整uint16旧入口域也保留：52*52*65535<2^28，+512仍安全，最后Clip1023。
#define SIX32 PADDL X5,X0; PADDL X4,X1; MOVOU X1,X6; PSLLL $2,X1; PADDL X6,X1; PADDL X3,X2; MOVOU X2,X6; PSLLL $2,X2; PADDL X6,X2; PSLLL $2,X2; PSUBL X1,X0; PADDL X2,X0
