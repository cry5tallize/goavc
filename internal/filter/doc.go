// Package filter 实现去块滤波（Deblocking Filter）。
//
// 编解码共用同一实现：编码器的本地重建与解码器的重建必须走完全相同的
// 滤波逻辑，否则参考帧漂移会逐帧累积。
//
// 关键约束：
//   - 边界强度 bS 的判定顺序必须与规范一致（先判 intra/编码块标志，
//     再判 MV 与残差差异），顺序不同会得到不同的 bS；
//   - alpha/beta 阈值表是 QP 的函数，索引越界必须夹紧而不是回绕；
//   - slice 边界与图像边界不滤波，但"是否边界"的判断依赖 slice 结构，
//     因此滤波函数需要显式的边界掩码，不能只看像素。
//   - 8/10-bit 共用泛型滤波核心；高位深 alpha、beta、tc0 乘
//     2^(bitDepth-8)，弱滤波 tc 的 +1/+2 和强滤波的 +2 不缩放；
//   - QP 必须先移除 QpBdOffset，缓冲跨度与边界位置以采样而非字节计。
