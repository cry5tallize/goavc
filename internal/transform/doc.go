//
// 正向：4×4/8×8 整数变换、Hadamard（亮度 DC 4×4、色度 DC 2×2）、
// 量化。反向：反量化、逆变换。
// 8/10-bit共用同一套内核：先用ScaleQP/ScaleChromaQP把语法QP转换为QP'，
// 量化与反量化只接受0..MaxScaledQP，逆变换归一化始终为>>6。
//
// 关键约束：
//   - 必须使用规范定义的整数变换，禁止用浮点 DCT 近似替代：
//     浮点实现无法保证编解码两侧逐比特一致；
//   - 正向与反向的移位量必须成对推导，任何一侧改动都要同步更新解析解测试；
//   - 量化后的系数要检查取值范围，越界（尤其是大 QP + 大残差）必须
//     做裁剪而不是回绕。
