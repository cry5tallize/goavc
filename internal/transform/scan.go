// Package transform 实现 H.264 的整数变换、反量化与扫描表。
//
// 编码器与解码器必须共用同一份实现（docs/architecture.md §3）：
// 解码器用它做残差重建，编码器用它做本地重建。任何“两份实现互相验证”
// 的想法都会导致两侧一起漂移，因此这里不提供第二套等价函数。
//
// M2 只实现 4×4 路径与 4×4/2×2 DC 路径；8×8 变换属于 M3。
package transform

// Zigzag4x4 把扫描序号映射到 4×4 块的光栅下标（row*4+col）。
//
// 规范 8.5.13 的系数扫描顺序：
//
//	0  1  5  6
//	2  4  7 12
//	3  8 11 13
//	9 10 14 15
//
// 表中第 k 项是扫描序号 k 对应的光栅下标。
var Zigzag4x4 = [16]int{
	0, 1, 4, 8, 5, 2, 3, 6,
	9, 12, 13, 10, 7, 11, 14, 15,
}

// LumaDCScan 是 I16×16 亮度 DC 块的扫描表。
//
// Spec: 8.5.6。使用规范的空间光栅布局，与 Zigzag4x4 相同；
// 不混入其他实现的转置存储或 8×8 分组编号。
var LumaDCScan = [16]int{
	0, 1, 4, 8, 5, 2, 3, 6,
	9, 12, 13, 10, 7, 11, 14, 15,
}

// DC2x2Scan 是 2×2 色度 DC 块的扫描顺序。
//
// 2×2 块没有 zigzag 概念，按光栅顺序（0,1,2,3）读取；保留独立符号是为了
// 让调用点显式表达“这是 DC 块，不做 4×4 扫描”，避免误用 Zigzag4x4。
var DC2x2Scan = [4]int{0, 1, 2, 3}
