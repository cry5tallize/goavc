// Package picture 实现编解码共享的图像存储布局。
//
// 与公共 API 的 h264.Frame 的区别：Frame 是"给别人看的视图"，
// picture 是"内部工作缓冲"——包含宏块对齐的编码尺寸、行对齐的 stride、
// 边缘扩展区（用于运动补偿越界读取）、以及缓冲池管理。
//
// 关键约束：
//   - 编解码必须使用同一套布局，否则本地重建与解码重建会出现
//     一像素级别的错位，且极难定位；
//   - 边缘扩展区的内容必须在每次重建后刷新，运动补偿可以读到图像外，
//     读到未初始化内存会直接破坏确定性。
