//go:build ignore

// 本地 CSV 保存 H.264 表 9-12..9-24 的数值；生成器只输出 Go 常量表，
// 无网络访问，不依赖 FFmpeg/x264 或其他外部工具。
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"os"
	"strconv"
)

func main() {
	f, err := os.Open("context_init.csv")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil {
		panic(err)
	}
	if len(rows) != 461 {
		panic("expected header and 460 context rows")
	}
	var tables [4][460][2]int
	for i, row := range rows[1:] {
		if len(row) != 9 {
			panic("expected 9 CSV fields")
		}
		id, err := strconv.Atoi(row[0])
		if err != nil || id != i {
			panic("context index mismatch")
		}
		for t := 0; t < 4; t++ {
			for j := 0; j < 2; j++ {
				v, err := strconv.Atoi(row[1+2*t+j])
				if err != nil || v < -128 || v > 127 {
					panic("invalid initialization coefficient")
				}
				tables[t][i][j] = v
			}
		}
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by gen_tables.go; DO NOT EDIT.\n\npackage cabac\n\n// Spec: H.264 tables 9-12..9-24; I, PB init_idc 0/1/2.\nvar initMN = [4][460][2]int8{")
	for _, table := range tables {
		fmt.Fprintln(&b, "{")
		for i, pair := range table {
			fmt.Fprintf(&b, "{%d,%d},", pair[0], pair[1])
			if i%8 == 7 {
				fmt.Fprintln(&b)
			}
		}
		fmt.Fprintln(&b, "\n},")
	}
	fmt.Fprintln(&b, "}")
	data, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("tables_gen.go", data, 0644); err != nil {
		panic(err)
	}
}
