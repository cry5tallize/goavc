//go:build ignore

// 本地 CSV 保存 H.264 初始化数值及规范中重复的区间；生成器只输出 Go 表，
// 无网络访问，不依赖 FFmpeg/x264 或其他外部工具。
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"os"
	"strconv"
)

func main() {
	f, err := os.Open("context_init.csv")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil {
		panic(err)
	}
	if len(rows) != 461 {
		panic("expected header and 460 context rows")
	}
	var tables [4][1024][2]int
	for i, row := range rows[1:] {
		if len(row) != 9 {
			panic("expected 9 CSV fields")
		}
		id, err := strconv.Atoi(row[0])
		if err != nil || id != i {
			panic("context index mismatch")
		}
		for t := 0; t < 4; t++ {
			for j := 0; j < 2; j++ {
				v, err := strconv.Atoi(row[1+2*t+j])
				if err != nil || v < -128 || v > 127 {
					panic("invalid initialization coefficient")
				}
				tables[t][i][j] = v
			}
		}
	}
	// 扩展数值来自 H.264 (2007)/Amd.2 表 9-24a..9-24i。
	// alias 每行表示 [first,last] 与从 source 开始的规范数值完全相同。
	// 表9-24d/e的8×8块按帧sig、场sig、帧last、场last、level排列，
	// 不同于亮度402..459的排列；CSV须按这五个语义区间逐段别名。
	a, err := os.Open("context_alias.csv")
	if err != nil {
		panic(err)
	}
	defer a.Close()
	aliases, err := csv.NewReader(a).ReadAll()
	if err != nil {
		panic(err)
	}
	next := 460
	for _, row := range aliases[1:] {
		if len(row) != 3 {
			panic("expected 3 alias CSV fields")
		}
		var v [3]int
		for i := range v {
			v[i], err = strconv.Atoi(row[i])
			if err != nil {
				panic("invalid alias index")
			}
		}
		first, last, source := v[0], v[1], v[2]
		if first != next || last < first || last >= 1024 || source < 0 || source+last-first >= first {
			panic("invalid or non-contiguous alias range")
		}
		for t := range tables {
			for i := first; i <= last; i++ {
				tables[t][i] = tables[t][source+i-first]
			}
		}
		next = last + 1
	}
	if next != 1024 {
		panic("expected aliases through context 1023")
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by gen_tables.go; DO NOT EDIT.\n\npackage cabac\n\n// Spec: H.264 initialization tables; I, PB init_idc 0/1/2.\nvar initMN = [4][1024][2]int8{")
	for _, table := range tables {
		fmt.Fprintln(&b, "{")
		for i, pair := range table {
			fmt.Fprintf(&b, "{%d,%d},", pair[0], pair[1])
			if i%8 == 7 {
				fmt.Fprintln(&b)
			}
		}
		fmt.Fprintln(&b, "\n},")
	}
	fmt.Fprintln(&b, "}")
	data, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("tables_gen.go", data, 0644); err != nil {
		panic(err)
	}
}
