// Package motion 实现运动估计（仅编码器使用）。
//
// 覆盖 SAD/SATD 代价、全搜索、菱形搜索、六边形搜索、多分辨率搜索、
// 半像素与四分之一像素细化、MV 预测。
//
// 关键约束：
//   - 代价函数与搜索策略分离：搜索算法只依赖代价函数接口，
//     这样 SIMD 优化 SAD 不会影响搜索逻辑；
//   - 所有搜索必须以"图像边界"为硬约束，越界候选直接判为不可用，
//     而不是靠后续裁剪兜底（裁剪会让代价失真，选错 MV）；
//   - 运动估计不影响码流正确性，但影响码率与画质，因此任何算法改动
//     都必须附 PSNR/码率对比数据。
